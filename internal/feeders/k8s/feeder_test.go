// Conformance (T061, US3 scenarios 1–3).
//
// testdata/baseline-shop is this connector's acceptance test: the shop of
// deploy/kind/otel-demo/minimal, delivered as one informer list, must produce the forty events
// fixtures/baseline-topology-01 records for `k8s:demo`. TestBaselineMatchesPublishedFixture
// compares the two line by line and says exactly where they differ and why.

// testFeeder is the feeder under the synthetic corpora's configuration.
func testFeeder(t *testing.T) *k8sfeeder.Feeder {
	t.Helper()
	f, err := k8sfeeder.New(fixtureOptions(), nil)
	if err != nil {
		t.Fatalf("new feeder: %v", err)
	}
	return f
}

// kindFeeder is the feeder as the live run of 2026-09-16 configured it, which is the command
// line deploy/kind/README.md documents. testdata/kind-shop was recorded through it, so nothing
// but these options reproduces that corpus.
func kindFeeder(t *testing.T) *k8sfeeder.Feeder {
	t.Helper()
	f, err := k8sfeeder.New(kindOptions(), nil)
	if err != nil {
		t.Fatalf("new feeder: %v", err)
	}
	return f
}

// kindShopDir is the recorded corpus of the live run.
const kindShopDir = "testdata/kind-shop"

func kindOptions() k8sfeeder.Options {
	return k8sfeeder.Options{
		SourceID:    "k8s:kind",
		ClusterName: "sre-agent-demo",
		Namespaces:  []string{"shop"},
		OwnerLabels: []string{"team"},
		Environment: "prod",
		// The kind recording and fixtures/baseline-topology-01 were both taken before
		// ADR-0005 D6 added `Pointer.join_keys`, so they are replayed under the pointer shape
		// they were recorded with — the same move IDFormatCompat makes for the otel baseline.
		// A live run emits the join keys; the corpora generated by TestGenerateTestdata are
		// recorded with them and prove it. See feeder.PointerCompat.
		PointerCompat: feeder.PointerCompatNoJoinKeys,
	}
}

