// TestConformanceKindShopShuffle is the third leg of testkit.Conformance, and it is the test
// that was skipped for the whole of the live run of 2026-09-16.
//
// The synthetic corpora hid the problem because every payload in them carries the same whole-
// second arrival time, so permuting them inside the 60s reordering window permutes nothing that
// matters. A real informer list does not: the 32 payloads of testdata/kind-shop arrive
// microseconds apart, and the feeder used to stamp the initial list's `valid_at` — and the
// extent of the checkpoint that closed it — from the arrival time of whichever payload it saw
// first. Reordering them moved every initial-list fact by a few microseconds, which is a
// valid-time state that depends on arrival order: FR-021 and FR-048 say it must not be.
//
// What fixed it is in three places and none of them is here. The initial list carries FR-011's
// unknown start instead of a guessed instant (Feeder.validFor); the checkpoint that closes it
// takes its extent from the marker payloads rather than from the earliest and latest arrival
// (Feeder.closeListAt); and an object seen within ListSettle of the marker is initial state
// however late the informers' own dispatch delivered it. Six seeded permutations now emit the
// same 63 events.
func TestConformanceKindShopShuffle(t *testing.T) {
	testkit.Shuffle(t, kindFeeder(t), kindShopDir)
}

